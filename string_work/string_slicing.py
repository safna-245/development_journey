#slicing :extract a portion from a sequence

text = "A man, a plan, a canal panama"

substr = text[17:22]

print(substr)

substr2 = text[:17]

print(substr2)

substr3 = text[17:]

print(substr3)

substr4 = text[9:13]

print(substr4)

substr5 = text[23:]

print(substr5)

substr6 = text[:5]

print(substr6)

copy_str = text[:]

print(copy_str)
